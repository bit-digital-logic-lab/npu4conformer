#!/usr/bin/env python3
"""Freeze the independent reference metadata for ds_matrix_reuse.

Hashes: gold model, RTL, tests, scripts, docs, patch, every fixture file, and
the read-only v023 files used as the RTL reference.  Does not include logs.
Run this once after the final regression; check_freeze.py can then be rerun.
"""
import hashlib
import json
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V23 = Path("/home/yang/Desktop/项目/v023_repair/ds_matrix")

FILES = []
FILES += sorted((ROOT / "candidate" / "rtl").glob("*.sv"))
FILES += sorted((ROOT / "tests").glob("*.sv"))
FILES += [ROOT / "scripts" / n for n in
          ("gold_reuse.py", "run_all.sh", "collect_metrics.py", "check_capacity.py")]
FILES += [ROOT / n for n in ("INTERFACE.md", "REVIEW.md", "WRITEBACK_INTERFACE.md",
                             "patches/writeback_interface_v1.patch")]
for d in sorted((ROOT / "fixtures").iterdir()):
    if d.is_dir():
        FILES += [d / "manifest.json", d / "init.hex", d / "exp_c.txt"]

V23_FILES = [
    V23 / "candidate/rtl/block_engine_prefetch_v2.sv",
    V23 / "candidate/rtl/block_storage_stream_v2.sv",
    V23 / "candidate/rtl/operand_banks_dual_v2.sv",
    V23 / "candidate/rtl/c_cache_banked4_pipe.sv",
    V23 / "candidate/rtl/block_address_v020.sv",
    V23 / "candidate/rtl/array16_w7_c48_cfg.sv",
    V23 / "candidate/rtl/pe_w7_c48_cfg.sv",
    V23 / "candidate/rtl/axi_dma_v020_multi_v2.sv",
    V23 / "tests/tb_engine_p2.sv",
    V23 / "tests/txn_dma_bfm.sv",
]


def sha(p):
    h = hashlib.sha256()
    with p.open("rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main():
    entries = {}
    for p in FILES:
        if not p.exists():
            raise SystemExit(f"missing {p}")
        entries[str(p.relative_to(ROOT))] = {"sha256": sha(p), "bytes": p.stat().st_size}
    v23 = {}
    for p in V23_FILES:
        if not p.exists():
            raise SystemExit(f"missing read-only reference {p}")
        v23[str(p)] = {"sha256": sha(p), "bytes": p.stat().st_size}

    # verify each fixture manifest's own hashes
    fixtures = {}
    for d in sorted((ROOT / "fixtures").iterdir()):
        if not d.is_dir():
            continue
        m = json.loads((d / "manifest.json").read_text())
        ok_init = sha(d / "init.hex") == m["sha256_init"]
        ok_exp = sha(d / "exp_c.txt") == m["sha256_exp"]
        if not (ok_init and ok_exp):
            raise SystemExit(f"fixture manifest mismatch: {d}")
        fixtures[d.name] = {
            "M": m["M"], "N": m["N"], "K": m["K"],
            "C_VALID": m["C_VALID"], "seed": m["seed"],
            "positions": m["positions"], "clip": m["clip"],
            "c_mode": m["c_mode"], "a_mode": m["a_mode"], "w_mode": m["w_mode"],
            "bad_parity": m["bad_parity"],
            "sha256_init": m["sha256_init"], "sha256_exp": m["sha256_exp"],
            "manifest_ok": True,
        }

    doc = {
        "task": "ds_matrix_reuse",
        "frozen_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "gold_model": "scripts/gold_reuse.py (independent integer model; not RTL-derived)",
        "note": "Fixtures are generated by gold_reuse.py and are not derived from any RTL or old PASS.",
        "files": entries,
        "fixtures": fixtures,
        "v023_readonly_reference": v23,
    }
    (ROOT / "REFERENCE_FREEZE.json").write_text(json.dumps(doc, indent=2) + "\n")
    print(f"frozen {len(entries)} files, {len(fixtures)} fixtures, "
          f"{len(v23)} read-only v023 files")


if __name__ == "__main__":
    main()
