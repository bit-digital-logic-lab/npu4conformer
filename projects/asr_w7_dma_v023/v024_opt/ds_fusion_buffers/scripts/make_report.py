w("   matrix 等待（`stat_bank_stall_cycles`），**不清 pending、不丢 tile**。")
w("4. `done` 仍要求：engine done、writer idle、所有 bank 为空、")
w("   `tiles_acked == ceil(M/32)*ceil(N/32)`、且 writer 的 `dma_done`（含")
w("   `b_out==0`）已发生。")
w()
